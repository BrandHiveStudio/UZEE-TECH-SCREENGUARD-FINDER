export interface WhatsAppOrderDetails {
  customerName?: string;
  customerPhone?: string;
  phoneModel: string;
  variant: "super_d" | "privacy" | "matte" | "borderless";
  urgency: "COUNTER_WAITING" | "ADVANCE_ORDER";
  advancePaymentOrNotes?: string;
}

export const VARIANT_LABELS: Record<string, { label: string; icon: string }> = {
  super_d: { label: "Super-D / Clear", icon: "✨" },
  privacy: { label: "Privacy / Anti-Spy", icon: "🕶️" },
  matte: { label: "Matte / Frosted", icon: "🌫️" },
  borderless: { label: "Borderless / Full Glue", icon: "🔲" },
};

export function formatWhatsAppPhone(phone?: string | null): string {
  if (!phone) return "";
  // Strip leading +, whitespace, dashes, parentheses, and all non-digits
  const digits = phone.replace(/\+/g, "").replace(/\s/g, "").replace(/[^\d]/g, "");
  // If local Sri Lankan 07X... format without country code, convert to 947X...
  if (digits.startsWith("0") && digits.length === 10) {
    return "94" + digits.slice(1);
  }
  return digits;
}

const RAW_DEFAULT_SUPPLIER = process.env.NEXT_PUBLIC_DEFAULT_SUPPLIER_WHATSAPP || "94770000000";
const DEFAULT_SUPPLIER = formatWhatsAppPhone(RAW_DEFAULT_SUPPLIER) || "94770000000";
const STORAGE_KEY = "uzee_active_supplier_whatsapp";

export function getActiveSupplierNumber(): string {
  if (typeof window === "undefined") {
    return DEFAULT_SUPPLIER;
  }
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && saved.trim()) {
      const sanitized = formatWhatsAppPhone(saved.trim());
      if (sanitized) return sanitized;
    }
    return DEFAULT_SUPPLIER;
  } catch {
    return DEFAULT_SUPPLIER;
  }
}

export function setActiveSupplierNumber(num: string): void {
  if (typeof window === "undefined") return;
  try {
    const sanitized = formatWhatsAppPhone(num);
    localStorage.setItem(STORAGE_KEY, sanitized);
  } catch (e) {
    console.error("Failed to persist supplier WhatsApp number", e);
  }
}

export function generateWhatsAppOrderUrl(details: WhatsAppOrderDetails, supplierPhone?: string): string {
  const activeSupplier = formatWhatsAppPhone(supplierPhone) || getActiveSupplierNumber();
  const now = new Date();
  const timeStr = now.toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
  }) + " at " + now.toLocaleTimeString("en-US", { hour: "2-digit", minute: "2-digit" });

  const urgencyLabel =
    details.urgency === "COUNTER_WAITING"
      ? "🚨 *CUSTOMER WAITING AT COUNTER (IMMEDIATE)*"
      : "📋 *ADVANCE CUSTOMER RESERVATION*";

  const variantObj = VARIANT_LABELS[details.variant] || { label: details.variant, icon: "📦" };

  const lines = [
    `⚡ *URGENT SCREEN GUARD REQUEST — UZEE TECH*`,
    `----------------------------------------`,
    urgencyLabel,
    `📱 *Model Required:* ${details.phoneModel.trim()}`,
    `${variantObj.icon} *Finish / Variant:* ${variantObj.label}`,
    details.customerName?.trim() ? `👤 *Customer Name:* ${details.customerName.trim()}` : null,
    details.customerPhone?.trim() ? `📞 *Customer Contact:* ${details.customerPhone.trim()}` : null,
    details.advancePaymentOrNotes?.trim() ? `💵 *Notes / Advance:* ${details.advancePaymentOrNotes.trim()}` : null,
    `⏰ *Timestamp:* ${timeStr}`,
    `📍 *Dispatched from:* UZEE TECH Retail Counter`,
    `----------------------------------------`,
    `_Please reply with stock confirmation & estimated dispatch time._`,
  ].filter(Boolean);

  const message = lines.join("\n");
  return `https://wa.me/${activeSupplier}?text=${encodeURIComponent(message)}`;
}

export function generateSupplierPOWhatsAppUrl(
  items: Array<{ boxNumber: string; title: string; currentStock: number; suggestedQty: number; priority: string }>,
  supplierPhone?: string
): string {
  const activeSupplier = formatWhatsAppPhone(supplierPhone) || getActiveSupplierNumber();
  const now = new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
  });

  const lines = [
    `📦 *UZEE TECH — STOCK REORDER PURCHASE REQUEST*`,
    `📅 *Date:* ${now}`,
    `📊 *Total Line Items:* ${items.length}`,
    `----------------------------------------`,
    ...items.slice(0, 30).map((item, idx) => {
      const priorityEmoji = item.priority === "CRITICAL" ? "🔴" : item.priority === "HIGH VELOCITY" ? "⚡" : "📦";
      return `${idx + 1}. [${item.boxNumber}] *${item.title}*\n   ${priorityEmoji} Current: ${item.currentStock} pcs | *Reorder: +${item.suggestedQty} pcs*`;
    }),
    ...(items.length > 30 ? [`\n_...and ${items.length - 30} more items in full PDF PO._`] : []),
    `----------------------------------------`,
    `Generated by UZEE TECH ScreenGuard Finder System.`,
    `Please confirm receipt and dispatch schedule.`,
  ];

  const message = lines.join("\n");
  return `https://wa.me/${activeSupplier}?text=${encodeURIComponent(message)}`;
}

